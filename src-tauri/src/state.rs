//! Состояние приложения, живущее всё время работы процесса.

use crate::fsx::paths::DataDir;

/// Хранится в Tauri и достаётся командам через `tauri::State`.
///
/// Здесь намеренно нет ни `Mutex`, ни `RwLock`: поле только одно и после
/// старта не меняется, а неизменяемые данные безопасно читать из любого
/// количества потоков без всякой синхронизации. Блокировка появится тогда,
/// когда появится изменяемое состояние (список буферов в задаче 4), и тогда же
/// будет понятно, какая именно нужна.
pub struct AppState {
    pub data_dir: DataDir,
    /// Сообщения, которые надо показать пользователю сразу после старта:
    /// например, что папка рядом с приложением недоступна на запись.
    pub startup_notices: Vec<String>,
}
