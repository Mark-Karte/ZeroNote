//! Состояние приложения, живущее всё время работы процесса.

use std::sync::Mutex;

use crate::fsx::paths::DataDir;
use crate::model::buffer::Buffers;

/// Хранится в Tauri и достаётся командам через `tauri::State`.
pub struct AppState {
    /// Где лежат данные. После старта не меняется, поэтому без блокировки:
    /// неизменяемые данные безопасно читать из любого числа потоков.
    pub data_dir: DataDir,

    /// Сообщения, которые надо показать пользователю сразу после старта.
    pub startup_notices: Vec<String>,

    /// Реестр открытых буферов.
    ///
    /// `Mutex`, потому что это единственное изменяемое состояние, а команды
    /// Tauri исполняются на нескольких потоках: без блокировки компилятор
    /// такой код просто не примет. Взят самый простой вариант, а не `RwLock`:
    /// операции здесь короткие, и читателей, которые мешали бы друг другу,
    /// не бывает.
    ///
    /// Важное правило пользования: блокировку держать ровно на время работы
    /// со списком и не звать под ней ничего, что лезет на диск. Иначе
    /// медленная запись файла заморозит все остальные команды.
    pub buffers: Mutex<Buffers>,
}
