//! Сведения о среде, в которой работает окно.

use tauri::path::BaseDirectory;
use tauri::Manager;

/// Имя файла уведомлений о сторонних компонентах — и в репозитории,
/// и рядом с установленной программой.
const NOTICES: &str = "THIRD-PARTY-NOTICES.md";

/// Путь к файлу уведомлений о сторонних компонентах (приёмка этапа 17).
///
/// Файл — ресурс сборки: установщик кладёт его рядом с программой, а при
/// отладке Tauri копирует его рядом с отладочной сборкой. Путь до ресурсов
/// знает только ядро — окно спрашивает его здесь и открывает файл обычной
/// вкладкой.
///
/// `Option`: файла нет — значит нет (собрано без него или удалён руками);
/// окно скажет об этом словами.
///
/// `AppHandle` приходит от Tauri сам: команда объявляет его параметром,
/// и Tauri подставляет ручку приложения — через неё и спрашиваются пути.
#[tauri::command]
pub fn third_party_notices(app: tauri::AppHandle) -> Option<String> {
    let path = app.path().resolve(NOTICES, BaseDirectory::Resource).ok()?;
    path.is_file().then(|| path.to_string_lossy().into_owned())
}

/// Версия установленного в системе рантайма WebView2.
///
/// Спрашиваем систему, а не строку агента браузера. Edge с некоторых пор
/// сокращает её из соображений слежки: там остаётся старший номер, а младшие
/// заменены нулями — `152.0.0.0`. В отчёте об ошибке это выглядит точным
/// числом и таковым не является, а разбор ведёт не туда.
///
/// `Option`, а не `Result`: не узнали — значит не узнали, и сведения покажутся
/// без этой строки. Окно с сообщением об ошибке было бы наказанием за нажатие
/// «о программе».
#[tauri::command]
pub fn webview_version() -> Option<String> {
    tauri::webview_version().ok()
}
