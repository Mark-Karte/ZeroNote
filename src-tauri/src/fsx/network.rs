//! Сетевые пути: `\\сервер\ресурс` и его родня (задача 139).
//!
//! Чтение такого пути — это вход на чужой сервер: Windows сама предлагает
//! ему учётные данные человека (хэш пароля NTLM), а недоступный сервер
//! держит вызов до тайм-аута. Поэтому путь, пришедший из текста файла или
//! из содержимого папки, сам по себе не читается никогда — только по явному
//! действию человека (Р-118, Р-202).

use std::path::{Component, Path, Prefix};

/// Ведёт ли путь на сетевой ресурс или мимо разбора путей Windows.
///
/// * `\\сервер\ресурс\…` — сетевой путь (`UNC`);
/// * `\\?\UNC\сервер\…` — он же в дословной записи;
/// * `\\.\…` и `\\?\нечто` без буквы диска — устройства и пути в обход
///   разбора: картинок и заметок там не бывает, а за ними может стоять
///   всё что угодно, в том числе тот же сервер.
///
/// Буква диска — `C:\…` и `\\?\C:\…` — не сеть, даже если это подключённый
/// сетевой диск: его человек подключил сам.
pub fn is_network(path: &Path) -> bool {
    match path.components().next() {
        Some(Component::Prefix(prefix)) => matches!(
            prefix.kind(),
            Prefix::UNC(..) | Prefix::VerbatimUNC(..) | Prefix::DeviceNS(..) | Prefix::Verbatim(..)
        ),
        _ => false,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn network_paths_are_recognised() {
        for path in [
            r"\\сервер\папка\x.png",
            r"\\127.0.0.1\c$\x.png",
            r"\\?\UNC\сервер\папка\x.png",
            r"\\.\pipe\что-то",
            r"\\?\GLOBALROOT\Device\x",
            "//сервер/папка/x.png",
        ] {
            assert!(is_network(Path::new(path)), "не узнан: {path}");
        }
    }

    #[test]
    fn local_paths_are_not_network() {
        for path in [
            r"C:\снимки\x.png",
            r"\\?\C:\снимки\x.png",
            r"снимки\x.png",
            r"..\общее\x.png",
            r"\снимки\x.png",
            "Z:/подключённый/x.png",
        ] {
            assert!(!is_network(Path::new(path)), "принят за сеть: {path}");
        }
    }
}
