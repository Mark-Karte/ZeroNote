/** Пункт всплывающего меню. Отдельным файлом: типы из компонентов не импортируются. */
export interface PopupItem {
  id: string;
  label: string;
  /** Заголовок раздела, показываемый над этим пунктом. */
  section?: string | undefined;
  /**
   * Черта над этим пунктом — раздел без названия.
   *
   * В контекстном меню называть группы нечем: «Правка», «Буфер обмена»
   * заняли бы половину меню и не сказали бы ничего, чего не видно по самим
   * пунктам. Черта делает ту же работу молча.
   */
  divider?: boolean | undefined;
  checked?: boolean | undefined;
  disabled?: boolean | undefined;
  /**
   * Сочетание клавиш вида `ctrl+shift+d` — как оно записано в раскладке.
   *
   * Именно сочетание, а не готовая подпись: подпись считает `labelOf`, и она
   * одна на всё приложение. Источник — реестр команд (Р-107), поэтому
   * переназначение в `keymap.toml` меняет и то, что написано в меню.
   */
  key?: string | undefined;
  /** Необратимое действие: помечается цветом, как в модальном диалоге (Р-093). */
  danger?: boolean | undefined;
  hint?: string | undefined;
}
