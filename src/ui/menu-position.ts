/**
 * Куда поставить меню, вызванное щелчком.
 *
 * Отдельным файлом и без единого обращения к DOM — ради проверяемости.
 * Расчёт положения это то место, где меню ошибается незаметно: уехавшее
 * за нижний край окна меню выглядит ровно как «меню не открылось», и искать
 * причину пойдут в обработчике щелчка.
 *
 * Правило простое и привычное по Windows: меню растёт вниз и вправо от точки,
 * а у края окна переворачивается на другую сторону — не сдвигается вдоль
 * края. Сдвиг накрыл бы то, по чему щёлкнули, а переворот оставляет точку
 * щелчка снаружи меню.
 */

export interface Size {
  width: number;
  height: number;
}

export interface Point {
  x: number;
  y: number;
}

export interface Placed {
  left: number;
  top: number;
}

/**
 * Положение левого верхнего угла меню.
 *
 * `margin` — поле, ближе которого к краю окна меню не подходит: у окна есть
 * своя рамка, и меню, прижатое к ней вплотную, читается как обрезанное.
 */
export function placeMenu(at: Point, menu: Size, viewport: Size, margin = 0): Placed {
  return {
    left: along(at.x, menu.width, viewport.width, margin),
    top: along(at.y, menu.height, viewport.height, margin),
  };
}

/** Место курсора в тексте: узкий прямоугольник высотой в строку. */
export interface Caret {
  left: number;
  top: number;
  bottom: number;
}

/**
 * Куда поставить список, всплывающий у курсора в тексте.
 *
 * Правило другое, чем у меню от щелчка, и разница существенная. Меню
 * переворачивается вокруг точки, оставляя её снаружи; здесь же снаружи должна
 * остаться **вся строка с курсором** — иначе список накроет то самое место,
 * которое подсказывает, и человек перестанет видеть, что набирает.
 * Поэтому вниз считается от низа строки, а вверх — от её верха.
 *
 * По горизонтали переворота нет вовсе: список привязан к началу ссылки,
 * и уехать он может только вправо, у самого края окна. Там он просто
 * прижимается к краю.
 */
export function placeAtCaret(
  caret: Caret,
  menu: Size,
  viewport: Size,
  margin = 0,
): Placed {
  const below = caret.bottom;
  const fits = below + menu.height <= viewport.height - margin;

  return {
    left: Math.max(margin, Math.min(caret.left, viewport.width - margin - menu.width)),
    top: fits ? below : Math.max(margin, caret.top - menu.height),
  };
}

/**
 * Одна ось. Обе считаются одинаково, и это не совпадение: «вниз» и «вправо» —
 * одно и то же правило, просто применённое к разным координатам.
 */
function along(at: number, size: number, limit: number, margin: number): number {
  // Обычный случай: помещается там, где щёлкнули.
  if (at + size <= limit - margin) return at;

  // Не помещается — переворачиваем на другую сторону точки.
  if (at - size >= margin) return at - size;

  // Не помещается ни так, ни так: меню шире или выше свободного места.
  // Прижимаем к началу — остаток уходит под прокрутку самого меню.
  // Math.min здесь важен: без него меню, которое всё-таки помещается,
  // но целиком левее точки, уехало бы правым краем за окно.
  return Math.max(margin, Math.min(at, limit - margin - size));
}
