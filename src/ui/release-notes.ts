/**
 * Заметки к выпуску на языке окна (задача 156).
 *
 * С 0.21.0 поле `notes` в `latest.json` двуязычное: сначала русская часть,
 * потом строка из трёх и более дефисов, потом английская. Диалог обновления
 * показывает только свою часть: русскую — русскому окну, английскую — всем
 * прочим, и своим переводам тоже.
 *
 * Разделитель — строка из дефисов, а не метка вида `[en]`: версии до 0.21.0
 * показывают заметки целиком, и черта между двумя частями читается там
 * как черта, а не как служебная запись. Разделителя нет — весь текст:
 * так выглядят заметки прежних выпусков.
 */

/** Строка из трёх и более дефисов, одна в строке. */
const SEPARATOR = /\r?\n[ \t]*-{3,}[ \t]*\r?\n/;

export function notesFor(notes: string, language: string): string {
  const parts = notes.split(SEPARATOR).map((part) => part.trim());
  if (parts.length < 2) return notes.trim();
  const russian = language.split('-')[0]!.toLowerCase() === 'ru';
  return (russian ? parts[0] : parts[1]) ?? '';
}
