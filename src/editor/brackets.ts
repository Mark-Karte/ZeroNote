import { EditorState, type Extension } from '@codemirror/state';
import type { EditorView } from '@codemirror/view';
import { language, matchBrackets } from '@codemirror/language';

/**
 * Парные скобки: подсветка пары и переход к ней.
 *
 * Само сопоставление — из разбора языка, как и свёртка: в дереве отмечено,
 * какой узел кому пара, и скобка внутри строки или комментария парой
 * не считается. Там, где дерева нет (обычный текст, языки из `legacy-modes`),
 * CodeMirror ищет пару простым просмотром текста — хуже, но не бесполезно.
 *
 * Автозакрытие живёт не здесь, а в наборе расширений: оно включается
 * настройкой и потому сидит в отсеке (`setup.ts`).
 */

/**
 * В прозе кавычка сама не закрывается.
 *
 * «Сказал» — это не начало строкового литерала, и вторая кавычка, приехавшая
 * сама, в русском тексте всегда лишняя. Скобки при этом закрываются: `(` в
 * прозе почти всегда парная.
 *
 * Прозой считается текст **без языка** — `.txt`, новый буфер, незнакомое
 * расширение. У markdown то же правило задано его собственными данными
 * (`langs.ts`), а языки программирования остаются с умолчанием CodeMirror:
 * там кавычка как раз парная.
 *
 * Устроено через данные языка, а не через свой обработчик ввода: `closeBrackets`
 * спрашивает их у состояния, и первый ответ побеждает. Когда язык есть, мы
 * молчим — и порядок расширений перестаёт что-либо значить.
 */
const proseBrackets: Extension = EditorState.languageData.of((state) =>
  state.facet(language) ? [] : [{ closeBrackets: { brackets: ['(', '[', '{'] } }],
);

/** Всё, что нужно скобкам, кроме автозакрытия: оно в отсеке (`setup.ts`). */
export function brackets(): Extension {
  return [proseBrackets];
}

/**
 * Куда прыгать от курсора, или `null`, если рядом нет парной скобки.
 *
 * Три попытки, и порядок у них не наш: это тот же порядок, в котором ищет
 * пару подсветка CodeMirror. Совпадение обязательно — иначе вышло бы, что
 * пара подсвечена, а перейти к ней нельзя, и объяснить это было бы нечем.
 *
 * Что означает каждая попытка:
 *
 * 1. закрывающая скобка **перед** курсором — идём назад к открывающей;
 * 2. открывающая скобка **перед** курсором — идём вперёд к закрывающей
 *    (это случай «курсор внутри только что набранной пары»);
 * 3. открывающая скобка **после** курсора — тоже вперёд.
 *
 * Курсор встаёт **снаружи** найденной пары: вперёд — за закрывающую, назад —
 * перед открывающей. Только так переход становится качелями: следующее
 * нажатие возвращает обратно. Встань курсор внутрь — второе нажатие ушло бы
 * к той же скобке, и переход работал бы в одну сторону.
 */
export function matchingPosition(state: EditorState): number | null {
  const pos = state.selection.main.head;

  const probes: [number, 1 | -1][] = [
    [pos, -1],
    [pos - 1, 1],
    [pos, 1],
  ];

  for (const [at, direction] of probes) {
    if (at < 0) continue;

    const match = matchBrackets(state, at, direction);
    // `matched: false` — скобка есть, а пары у неё нет. Прыгать некуда,
    // и это не ошибка: подсветка в этот момент как раз показывает красным.
    if (match?.matched && match.end) {
      return direction === 1 ? match.end.to : match.end.from;
    }
  }

  return null;
}

/**
 * Перейти к парной скобке.
 *
 * Курсор встаёт перед найденной скобкой — одинаково в обе стороны. Так
 * повторное нажатие возвращает обратно, и переход становится качелями,
 * а не движением в одну сторону.
 */
export function goToBracket(view: EditorView): boolean {
  const target = matchingPosition(view.state);
  if (target === null) return false;

  view.dispatch({
    selection: { anchor: target },
    scrollIntoView: true,
  });
  return true;
}
