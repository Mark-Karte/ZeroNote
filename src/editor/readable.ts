/**
 * Читаемая ширина: колонка текста и перенос (задача 58).
 *
 * Чистые правила отдельным модулем — их два, и оба неочевидны настолько,
 * что должны проверяться тестом, а не памятью.
 */

export interface ReadableContext {
  /** Общая настройка переноса строк (`[editor] wrap`). */
  wrap: boolean;
  /** Настройка читаемой ширины (`[editor] readable_width`). */
  readableWidth: boolean;
  /** Markdown ли на вкладке: колонка бывает только у него. */
  markdown: boolean;
}

/**
 * Показывать ли текст колонкой по центру окна.
 *
 * Только markdown (Р-156). В коде длина строки — часть смысла: там
 * выравнивают продолжения, таблицы и комментарии по столбцам, и колонка
 * в восемьдесят знаков резала бы их посередине.
 */
export function readableColumn(ctx: ReadableContext): boolean {
  return ctx.readableWidth && ctx.markdown;
}

/**
 * Переносить ли длинные строки на этой вкладке.
 *
 * **Колонка включает перенос, даже когда общая настройка его выключает.**
 * Без переноса абзац — это одна длинная строка, которая уходит за правый
 * край колонки и прокручивается; колонка, которую текст не замечает, —
 * не колонка, а поле для отступа слева.
 *
 * Тех, кто переносит markdown руками по восьмидесятому столбцу, это
 * не задевает вовсе: их строки короче колонки, и переносить в них нечего.
 */
export function wrapFor(ctx: ReadableContext): boolean {
  return ctx.wrap || readableColumn(ctx);
}
