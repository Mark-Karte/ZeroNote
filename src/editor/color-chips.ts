/**
 * Коды цвета в тексте заметки — `#rgb`, `#rgba`, `#rrggbb`, `#rrggbbaa`
 * (задача 130, ответ владельца на вопрос 5 плана этапа 18).
 *
 * Превью ставит перед кодом квадратик этого цвета — как VS Code в стилях;
 * у владельца так делал плагин Obsidian. Сам код не меняется ни цветом,
 * ни знаком: квадратик рисуется `::before` у куска (`editor.css`), в тексте
 * его нет, и копируется файл, а не экран (Р-160). Заливать код его цветом
 * значило бы подбирать к каждой заливке цвет текста — зашитый чёрный или
 * белый, которых у темы нет.
 *
 * Справа от кода — не буква и не цифра: `#abcdefg` — не цвет, а `#abc`
 * внутри `#abcde` — тем более. Слева граница не нужна: `#ff429e#706910`
 * из заметки владельца — два цвета подряд.
 */
const HEX_COLOR = /#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})(?![0-9A-Za-z_])/g;

/** Где в тексте коды цвета: смещение от начала текста и сам код. */
export function hexColors(text: string): { at: number; color: string }[] {
  return [...text.matchAll(HEX_COLOR)].map((match) => ({ at: match.index, color: match[0] }));
}

/**
 * Узлы, где код цвета квадратика не получает: блок кода — там столбцы
 * держатся знаками, и квадратик сдвинул бы строку; адрес ссылки, сущность
 * HTML (`&#123456;`) и сырой HTML — не цвет. Строчный код — получает:
 * цвет в заметке чаще всего пишут именно так.
 */
export const NO_CHIPS: ReadonlySet<string> = new Set([
  'FencedCode',
  'CodeBlock',
  'URL',
  'Autolink',
  'Entity',
  'HTMLTag',
  'HTMLBlock',
]);
