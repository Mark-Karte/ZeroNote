import { version } from './version';

/**
 * Сведения о программе.
 *
 * Собираются здесь, а не в компоненте: показываются они в двух местах —
 * диалогом по команде палитры и карточкой в окне параметров, — и разойтись
 * эти два места не должны.
 *
 * Ссылки на страницу выпусков тут пока нет намеренно: репозитория ещё
 * не существует, он заводится в задаче 44. Ссылка на несуществующую
 * страницу хуже её отсутствия — она обещает то, чего нет.
 */

/** Название с номером версии. Первая строка любых сведений. */
export function nameAndVersion(): string {
  return `ZeroNote ${version}`;
}

/**
 * Сведения построчно — ровно то, что уходит в буфер обмена по кнопке.
 *
 * Лишнего в отчёте об ошибке быть не должно, а недостающее придётся
 * выспрашивать в переписке. Поэтому здесь только то, что отличает одну
 * установку от другой: наша версия и версия оболочки.
 *
 * Версия WebView2 нужна не из любопытства: окно рисует не наш код, а рантайм,
 * установленный в системе, и обновляется он сам по себе, независимо от нас.
 * Жалоба «у меня не видно стрелки табуляции» без его номера не
 * воспроизводится — у сообщившего и у нас на экране разные программы.
 */
export function aboutLines(shell: string | null): string[] {
  return [
    nameAndVersion(),
    shell === null ? 'WebView2: версия неизвестна' : `WebView2 ${shell}`,
  ];
}

export function aboutText(shell: string | null): string {
  return aboutLines(shell).join('\n');
}
