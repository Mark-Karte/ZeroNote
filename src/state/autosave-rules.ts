import type { Buffer } from '../ipc/files';

/**
 * Что автосохранение вправе записать (Р-141).
 *
 * Отдельным модулем и чистой функцией — ради проверяемости. Правило одно
 * и звучит так: **автосохранение пишет только то, что можно записать,
 * ни о чём не спрашивая и ничего не теряя**. Всё остальное остаётся
 * изменённым, и точка на вкладке об этом говорит.
 *
 * Ручное сохранение в трёх местах задаёт вопрос: «куда сохранить» у буфера
 * без файла, «к какому типу привести переносы» у смешанных (Р-018) и «файл
 * изменила другая программа, перезаписать?» при расхождении с диском.
 * Диалог, всплывший сам по себе, — худшее, что может сделать автосохранение:
 * человек не нажимал ничего, а его о чём-то спрашивают поверх текста.
 */
export function autosavable(meta: Buffer): boolean {
  // Нечего сохранять.
  if (!meta.modified) return false;

  // Нет файла на диске: сохранение открыло бы системный диалог «сохранить как».
  if (meta.path === null) return false;

  // Путь есть, а файла по нему нет: его удалили или переименовали снаружи,
  // либо он не открылся при восстановлении сессии. Запись **создала бы**
  // файл заново, а создание — действие крупнее обновления, и делать его
  // без команды нельзя. Найдено живой проверкой: удалённые с диска файлы
  // возвращались сами через две секунды после первой же правки.
  if (meta.disk === null) return false;

  // Смешанные переносы: запись привела бы их к одному виду, а решать это
  // за пользователя мы не будем — решение владельца, задача 51.
  if (meta.eolMixed) return false;

  // Файл не раскодировался без потерь: запись закрепила бы потерю.
  if (meta.lossy) return false;

  // Только для чтения и упрощённый режим больших файлов: там и ручное
  // сохранение не работает.
  if (meta.readOnly || meta.large) return false;

  return true;
}
