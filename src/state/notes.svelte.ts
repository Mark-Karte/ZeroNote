/**
 * Отметка о том, что заметок стало больше (задача 99, находка приёмки).
 *
 * Календарь помечает дни, за которые заметка написана, и список этих дней
 * ему отдаёт ядро. Пока заметку создавали щелчком по самому календарю, он
 * перечитывал список сам; но её создаёт ещё и кнопка «Заметка на сегодня»
 * в шапке панели, и команда из палитры, и заготовка. Тогда календарь
 * оставался со вчерашним ответом: файл в дереве есть, а день не помечен.
 *
 * Счётчик, а не признак: важно каждое событие, а не «было ли оно вообще».
 * Слушать вместо этого файловую систему было бы честнее по букве, но дороже
 * по делу: пометки меняются от наших же действий, а наблюдатель за папкой
 * ради углового виджета — лишний.
 *
 * **Цена названа:** заметка, созданная снаружи (в другой программе), календарь
 * не помечает до смены месяца или возврата к панели.
 */
export const notes = $state<{ created: number }>({ created: 0 });

/** Сказать, что заметка создана: календарь перечитает свои пометки. */
export function noteCreated(): void {
  notes.created += 1;
}
