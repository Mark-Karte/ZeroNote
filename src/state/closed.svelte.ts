/**
 * Закрытые вкладки: `Ctrl+Shift+T` (задача 86).
 *
 * Привычка из браузера, и ожидание у неё браузерное: вернуть последнюю
 * закрытую, потом предыдущую, и так далее.
 *
 * **Помним только вкладки с файлом на диске** (Р-219). Безымянный буфер
 * возвращать нечем и не нужно: его закрытие спрашивает про несохранённое,
 * и «не сохранять» — это ответ человека «выбросить», а черновик к этому
 * времени уже удалён. Возвращать выброшенное по нажатию значило бы спорить
 * с его же ответом.
 *
 * Как и история мест, модуль ничего не знает про вкладки: он держит стек
 * и решает, что с него снять. Кто открывает файл и куда его ставит —
 * не его дело.
 */

/** Что нужно знать, чтобы вернуть вкладку такой, какой её закрыли. */
export interface ClosedTab {
  path: string;
  /** Область, в которой вкладка была: туда же и вернётся, если она жива. */
  pane: number;
  /** Место в полосе вкладок: возвращённая встаёт туда, где стояла. */
  index: number;
  cursor: number;
  scrollTop: number;
  /** Язык, выбранный вручную. `null` — определять по имени файла. */
  language: string | null;
  /** Номера строк с закладками, с единицы. */
  bookmarks: number[];
}

/**
 * Сколько закрытых вкладок помнить.
 *
 * Двадцать — мера полезности, а не памяти: запись весит десяток чисел,
 * а дальше двадцатой человек уже не помнит, что закрывал.
 */
const LIMIT = 20;

/** Стек в руне: от него зависит доступность пункта меню. */
export const closed = $state<{ items: ClosedTab[] }>({ items: [] });

/** Для тестов: забыть всё. */
export function resetClosed(): void {
  closed.items.length = 0;
}

export function hasClosed(): boolean {
  return closed.items.length > 0;
}

/**
 * Запомнить закрытую вкладку.
 *
 * Повторное закрытие того же файла заменяет прежнюю запись, а не добавляет
 * вторую: иначе `Ctrl+Shift+T` дважды подряд открывал бы один и тот же файл,
 * а на второй раз — молча ничего.
 */
export function remember(tab: ClosedTab): void {
  const same = closed.items.findIndex((item) => samePath(item.path, tab.path));
  if (same >= 0) closed.items.splice(same, 1);

  closed.items.push(tab);
  if (closed.items.length > LIMIT) closed.items.shift();
}

/**
 * Снять последнюю запись, которая ещё имеет смысл.
 *
 * `isOpen` — «этот файл уже открыт». Такие записи пропускаются: человек
 * закрыл файл, потом открыл его сам, и возвращать нечего. Пропускаем молча
 * и берём следующую — так же, как история мест пропускает закрытые вкладки.
 */
export function takeClosed(isOpen: (path: string) => boolean): ClosedTab | null {
  while (closed.items.length > 0) {
    const item = closed.items.pop()!;
    if (!isOpen(item.path)) return item;
  }
  return null;
}

/**
 * Windows не различает регистр путей, и путь приходит откуда угодно:
 * из дерева, из палитры, из буфера обмена. Правило то же, что в ядре
 * (`index::writer::path_key`), и здесь оно нужно ровно затем же.
 */
function samePath(a: string, b: string): boolean {
  return a.replace(/\//g, '\\').toLowerCase() === b.replace(/\//g, '\\').toLowerCase();
}
