/**
 * Собственные модальные вопросы.
 *
 * Системный диалог Tauri умеет только два ответа — «да» и «отмена». Нам нужны
 * вопросы с тремя и более вариантами: к какому типу переносов привести файл,
 * что делать с изменившимся на диске файлом. Отсюда свой диалог.
 *
 * Заодно он выглядит по теме приложения, а не системным окном поверх
 * оформленного интерфейса.
 *
 * Устроено так, чтобы вопрос можно было задать из обычного кода в `actions/`,
 * а не только из компонента: функция возвращает обещание, которое разрешается,
 * когда пользователь выбрал.
 */

export interface Choice {
  id: string;
  label: string;
  /** Вариант по умолчанию: он получает фокус и срабатывает по Enter. */
  primary?: boolean;
  /** Отмена: срабатывает по Escape и при закрытии диалога. */
  cancel?: boolean;
  /**
   * Необратимый вариант: «не сохранять», «потерять правки».
   *
   * Помечается цветом опасности. Ради этого диалог и написан свой (Р-027):
   * в системном такой вариант неотличим от обычного, и нажать его случайно
   * стоит ровно тех данных, которые пользователь набирал.
   */
  danger?: boolean;
}

/**
 * Ход долгой работы: шаги, полоска, строка под ней (задача 104).
 *
 * Меняется на месте тем, кто работу ведёт, — диалог перерисовывается сам.
 */
export interface ProgressView {
  title: string;
  text: string;
  /** Шаги по порядку: пройденные отмечены, текущий выделен, будущие приглушены. */
  steps: string[];
  /** Номер текущего шага в `steps`. */
  step: number;
  /** Доля от 0 до 1; `null` — полоски нет, длина работы неизвестна. */
  fraction: number | null;
  /** Строка под полоской: байты, проценты, секунды. */
  detail: string;
  /** Предупреждение цветом внимания — например, тишина в сети. */
  warning: string;
  /**
   * Отмена, пока работу ещё можно снять; `null` — уже нельзя, кнопки нет.
   * Ставится только там, где отмена настоящая: кнопка, которая закрывает
   * окно, но не останавливает работу, обещала бы то, чего не делает.
   */
  cancel: (() => void) | null;
}

export interface ModalRequest {
  title: string;
  text: string;
  choices: Choice[];
  /** Диалог с полем ввода: ответом становится введённая строка. */
  input?: { initial: string } | undefined;
  resolve: (id: string | null) => void;
}

/**
 * Вопрос и ход работы живут порознь (задача 104).
 *
 * Ход работы — не вопрос: ответа у него нет, и закрывает его тот, кто работу
 * ведёт. Вопрос, пришедший посреди работы (файл изменился на диске), встаёт
 * поверх, а ответ на него возвращает ход работы на место. Живи они в одном
 * месте, вопрос стёр бы ход работы, и загрузка шла бы дальше невидимой.
 */
export const modal = $state<{ request: ModalRequest | null; progress: ProgressView | null }>({
  request: null,
  progress: null,
});

/**
 * Задать вопрос и дождаться ответа.
 *
 * Возвращает `null`, если пользователь отказался. Вызывающий код обязан
 * это учитывать: «отмена» никогда не должна означать «сделай хоть что-нибудь».
 */
export function askChoice(
  title: string,
  text: string,
  choices: Choice[],
): Promise<string | null> {
  return open({ title, text, choices });
}

/**
 * Спросить строку.
 *
 * Возвращает введённое или `null`, если пользователь отказался.
 *
 * Подпись кнопки задаётся вызывающим и не имеет умолчания по смыслу:
 * «Перейти», «Создать» и «Переименовать» — разные обещания, и одно вместо
 * другого читается как ошибка. Первая версия подписывала кнопку «Перейти»
 * всегда, потому что первым её позвал переход к строке.
 */
export function askInput(
  title: string,
  text: string,
  initial: string,
  confirm: string,
): Promise<string | null> {
  return open({
    title,
    text,
    input: { initial },
    choices: [
      { id: 'cancel', label: 'Отмена', cancel: true },
      { id: 'ok', label: confirm, primary: true },
    ],
  });
}

/**
 * Показать ход работы.
 *
 * Возвращает то, что видно на экране, — менять поля `view` на месте, — и
 * `close`. Щелчок мимо ход работы не закрывает; Escape нажимает «Отмену»,
 * если она есть.
 *
 * `close` закрывает только свой ход работы: если его уже сменил другой,
 * тот остаётся на месте.
 */
export function showProgress(initial: ProgressView): { view: ProgressView; close: () => void } {
  modal.progress = initial;

  // Читаем обратно из состояния: изменения должен видеть диалог, а видит он
  // отслеживаемую копию, а не объект, переданный сюда.
  const view = modal.progress as ProgressView;

  return {
    view,
    close: () => {
      if (modal.progress === view) modal.progress = null;
    },
  };
}

function open(request: Omit<ModalRequest, 'resolve'>): Promise<string | null> {
  // Два вопроса одновременно — ошибка в вызывающем коде, но подвесить
  // предыдущее обещание навсегда всё равно нельзя.
  modal.request?.resolve(null);

  return new Promise((resolve) => {
    modal.request = {
      ...request,
      resolve: (value) => {
        modal.request = null;
        resolve(value);
      },
    };
  });
}
