import { autosaveEnabled } from './settings.svelte';

/**
 * Автосохранение: когда писать (Р-141).
 *
 * Здесь только поводы и время; сама запись — в `actions/files`, потому что
 * это действие над файлами, как и всё остальное сохранение. Действие
 * подтягивается по требованию: иначе состояние ссылалось бы на действия,
 * а действия на состояние, и получился бы круг. Ввоз происходит не чаще
 * раза в две секунды, а не на каждое нажатие.
 *
 * Поводов два, и второй важнее первого (решение владельца, задача 51):
 *
 * * пауза после последней правки — та же, что у черновиков;
 * * **окно потеряло фокус или сменилась вкладка** — то есть человек ушёл
 *   к другой программе и ждёт, что на диске уже свежее.
 *
 * Черновики (инвариант 4) от этой настройки не зависят и пишутся всегда:
 * автосохранение — про удобство, черновики — про потерю данных.
 */

/** Та же пауза, что у черновиков: два числа в голове держать незачем. */
const DELAY_MS = 2000;

export const autosave = $state<{ problems: string[] }>({ problems: [] });

let timer: ReturnType<typeof setTimeout> | null = null;

function clear(): void {
  if (timer !== null) {
    clearTimeout(timer);
    timer = null;
  }
}

async function run(): Promise<void> {
  const { autosaveAll } = await import('../actions/files');
  const problems = await autosaveAll();

  // Список заменяется целиком, а не пополняется: жалоба про переполненный
  // диск, повторённая двадцать раз, — это не двадцать бед, а одна.
  // Полоса скрывается по набору сообщений (Р-094), и повтор её не вернёт.
  autosave.problems = problems;
}

/** Правка в редакторе: запись уйдёт на диск после паузы. */
export function scheduleAutosave(): void {
  if (!autosaveEnabled()) return;

  clear();
  timer = setTimeout(() => {
    timer = null;
    void run();
  }, DELAY_MS);
}

/**
 * Записать немедленно: окно теряет фокус или сменилась вкладка.
 *
 * Отложенная запись при этом отменяется — она бы сделала ту же работу второй
 * раз через две секунды.
 */
export function autosaveNow(): void {
  if (!autosaveEnabled()) return;

  clear();
  void run();
}
