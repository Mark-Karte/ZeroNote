import type { FileEdits } from '../ipc/edits';

/**
 * Замена по проекту: поле замены, её настройки и стек отмены (задача 88).
 *
 * **Отмена помнит пять последних замен, пока приложение открыто** — решение
 * владельца. Между запусками не хранится ничего: сессия — про вкладки,
 * а не про историю правок в чужих файлах, и обещание «отменю то, что вы
 * сделали вчера» приложение сдержать не может: файлы за это время правят
 * другими программами.
 *
 * Место стека — здесь, а не в ядре, по той же причине, что у истории мест
 * и закрытых вкладок: состояние, живущее ровно столько, сколько окно, живёт
 * во фронтенде. Ядро остаётся без памяти о том, что оно кому-то должно.
 */

/** Сколько замен помнит отмена (решение владельца). */
const LIMIT = 5;

/** Сделанная замена: чем она была и чем её вернуть. */
export interface DoneReplace {
  query: string;
  replacement: string;
  /** Запрос был выражением: об этом надо сказать в вопросе об отмене. */
  expression: boolean;
  /** Сколько совпадений заменено — для подписи в вопросе об отмене. */
  matches: number;
  /** Правки, возвращающие всё как было. Только по тем файлам, что записались. */
  undo: FileEdits[];
}

export const replace = $state<{
  /** Строка замены раскрыта. Свёрнута по умолчанию: панель — про поиск. */
  open: boolean;
  replacement: string;
  /** Идёт обход файлов. Пока идёт, кнопка предлагает прервать. */
  running: boolean;
  /**
   * Идёт запись на диск.
   *
   * Отдельно от обхода, потому что это разные обещания: обход можно
   * прервать, запись — нет. Признак нужен и потому, что запись тысяч файлов
   * занимает секунды: приёмка этапа 13 записала пять тысяч файлов за семь
   * секунд, и всё это время панель молчала.
   */
  writing: boolean;
  /** Чем кончилась последняя замена — строкой под полем. */
  done: string;
}>({
  open: false,
  replacement: '',
  running: false,
  writing: false,
  done: '',
});

// Переключатели «Aa», «|ab|» и «.*» живут не здесь, а в `project-search`:
// это свойства запроса, а запрос один на поиск и на замену (задача 89).
// Держать их у замены значило бы объяснять, почему выражение в поле есть,
// а список ищет по словам.

/**
 * Просьба к панели забрать фокус в поле замены.
 *
 * Счётчик, а не признак: повторный вызов команды при уже открытой панели
 * тоже обязан вернуть фокус, а признак «нужен фокус» второй раз не изменился
 * бы. Тот же приём, что у поиска по проекту.
 */
export const replaceFocusRequest = $state({ value: 0 });

/** Стек в руне: от него зависит доступность кнопки и пункта палитры. */
export const undoable = $state<{ items: DoneReplace[] }>({ items: [] });

/** Для тестов: забыть всё. */
export function resetReplaceHistory(): void {
  undoable.items.length = 0;
}

export function canUndoReplace(): boolean {
  return undoable.items.length > 0;
}

/** Что отменится следующим нажатием. */
export function lastReplace(): DoneReplace | null {
  return undoable.items.at(-1) ?? null;
}

/**
 * Запомнить сделанную замену.
 *
 * Замена, не изменившая ни одного файла, не запоминается: отменять нечего,
 * а пустая запись съела бы место в стеке из пяти и вытеснила настоящую.
 */
export function remember(entry: DoneReplace): void {
  if (entry.undo.length === 0) return;

  undoable.items.push(entry);
  if (undoable.items.length > LIMIT) undoable.items.shift();
}

/**
 * Снять последнюю замену.
 *
 * Только последнюю и в порядке «сначала свежая»: замены накладываются друг
 * на друга, и отмена третьей при живых четвёртой и пятой ничего бы не нашла
 * на прежних местах — сверка байтов отказала бы в правке молча, файл
 * за файлом.
 */
export function takeLastReplace(): DoneReplace | null {
  return undoable.items.pop() ?? null;
}
