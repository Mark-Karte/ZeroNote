/**
 * Короткие сообщения приложения.
 *
 * Это не ошибки: ошибки живут в полосе предупреждений, пока их не прочитают
 * (Р-032), и висеть там — их работа. Здесь другое — ответ на действие
 * человека, которому иначе ответить нечем. Нажал `Ctrl+F` над PDF: поиска
 * там нет, и молчание он прочитает как «окно зависло».
 *
 * Показывается той же полосой, чтобы не заводить второй вид сообщений,
 * и уходит само.
 */

export const notices = $state<{ items: string[] }>({ items: [] });

/** Сколько сообщение висит: хватает прочитать и не хватает надоесть. */
const LIFETIME_MS = 6000;

let timer: ReturnType<typeof setTimeout> | null = null;

/**
 * Сказать одну фразу. Одну, а не список: это ответ на нажатие, а не журнал.
 * Новое сообщение вытесняет прежнее — человек и спрашивал про новое.
 */
export function notify(text: string): void {
  notices.items = [text];

  if (timer !== null) clearTimeout(timer);
  timer = setTimeout(() => {
    notices.items = [];
    timer = null;
  }, LIFETIME_MS);
}
