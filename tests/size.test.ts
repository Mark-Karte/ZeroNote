import { describe, expect, it } from 'vitest';
import { fileSize } from '../src/ui/size';

/**
 * Вес файла в строке состояния.
 *
 * Приставки двоичные, как во всех приёмках проекта: разнобой между
 * «мегабайтом» установщика и «мегабайтом» строки состояния заметен ровно
 * тогда, когда числа сравнивают, — а сравнивают их в тот момент, когда
 * что-то пошло не так.
 */
describe('вес файла', () => {
  it('до килобайта показывается байтами', () => {
    expect(fileSize(0)).toBe('0 Б');
    expect(fileSize(1)).toBe('1 Б');
    expect(fileSize(1023)).toBe('1023 Б');
  });

  it('дальше растёт двоичными приставками', () => {
    expect(fileSize(1024)).toBe('1,0 КиБ');
    expect(fileSize(1024 * 1024)).toBe('1,0 МиБ');
    expect(fileSize(1024 * 1024 * 1024)).toBe('1,0 ГиБ');
  });

  /**
   * Дробная часть остаётся только там, где она и есть весь ответ.
   * «482,3 КиБ» с одного взгляда не читается, а «1,4 МиБ» против «1 МиБ» —
   * это разница, ради которой вес и показывают.
   */
  it('десятая доля только у малых чисел', () => {
    expect(fileSize(1024 * 1.4)).toBe('1,4 КиБ');
    expect(fileSize(1024 * 482.3)).toBe('482 КиБ');
    expect(fileSize(1024 * 1024 * 9.6)).toBe('9,6 МиБ');
    expect(fileSize(1024 * 1024 * 23.4)).toBe('23 МиБ');
  });

  /** Разделитель дробной части — запятая: подпись русская. */
  it('дробь пишется через запятую', () => {
    expect(fileSize(1024 * 2.5)).toContain(',');
    expect(fileSize(1024 * 2.5)).not.toContain('.');
  });

  /** Отсутствие числа — не повод показывать «NaN Б». */
  it('несуразное значение показывается прочерком', () => {
    expect(fileSize(Number.NaN)).toBe('—');
    expect(fileSize(-1)).toBe('—');
  });
});
