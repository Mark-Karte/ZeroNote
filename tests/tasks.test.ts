import { describe, expect, it } from 'vitest';
import { taskState, toggleChar } from '../src/editor/tasks';

/**
 * Знак задачи `- [ ]` (задача 91).
 *
 * Разбор знака проверяется отдельно от превью, потому что по нему правится
 * файл: щелчок меняет один знак в документе человека, и «похоже на задачу»
 * здесь недостаточно — надо ровно `[ ]`, `[x]` или `[X]`.
 */

describe('знак задачи', () => {
  it('различает снятую и сделанную', () => {
    expect(taskState('[ ]')).toBe('open');
    expect(taskState('[x]')).toBe('done');
    expect(taskState('[X]')).toBe('done');
  });

  /**
   * Всё, что не знак задачи, знаком задачи не считается. Иначе щелчок
   * заменил бы средний знак в чужой скобке.
   */
  it('отвергает всё остальное', () => {
    for (const bad of ['[]', '[  ]', '[y]', '( )', '[ ', ' ]', '[ ]x', '']) {
      expect(taskState(bad), `«${bad}» не знак задачи`).toBeNull();
    }
  });

  it('переключается в обе стороны', () => {
    expect(toggleChar('open')).toBe('x');
    expect(toggleChar('done')).toBe(' ');
  });

  /**
   * Сделанную задачу помечаем строчной `x`: так пишет Obsidian и почти все.
   * Заглавная `X` разбирается, но не воспроизводится.
   */
  it('ставит строчную x', () => {
    expect(toggleChar(taskState('[ ]')!)).toBe('x');
  });
});
