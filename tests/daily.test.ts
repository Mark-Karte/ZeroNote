import { describe, expect, it } from 'vitest';
import { stamp } from '../src/actions/daily';

/**
 * Дата и время для заметки на сегодня (задача 90).
 *
 * Считает их окно, а не ядро: у `std::time` нет часового пояса. Проверка
 * здесь ровно об этом — что берётся местное время, а не UTC. Ошибка в этом
 * месте не видна глазом: она проявляется вечером и у тех, кто живёт восточнее
 * Гринвича, то есть у владельца.
 */

describe('дата заметки на сегодня', () => {
  it('складывается из года, месяца и дня с нулями', () => {
    // Второе января — оба числа однозначные: без дополнения нулём вышло бы
    // «2026-1-2», и такие имена в дереве встали бы не по порядку.
    const { date, time } = stamp(new Date(2026, 0, 2, 9, 5));

    expect(date).toBe('2026-01-02');
    expect(time).toBe('09:05');
  });

  it('месяцы считаются с единицы, а не с нуля', () => {
    expect(stamp(new Date(2026, 11, 31, 23, 59)).date).toBe('2026-12-31');
  });

  /**
   * Главное: местное время, а не UTC. `toISOString` после девяти вечера
   * по Москве отдал бы завтрашний день — и команда открывала бы не ту
   * заметку, ровно тогда, когда её пишут.
   */
  it('берёт местный день, а не UTC', () => {
    const late = new Date(2026, 8, 8, 23, 30);
    const { date } = stamp(late);

    expect(date).toBe('2026-09-08');
    expect(date.slice(0, 10)).toBe(
      `${late.getFullYear()}-${String(late.getMonth() + 1).padStart(2, '0')}-${String(
        late.getDate(),
      ).padStart(2, '0')}`,
    );
  });
});
