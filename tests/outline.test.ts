import { describe, expect, it } from 'vitest';
import { Text } from '@codemirror/state';
import { activeHeading, outlineOf } from '../src/editor/outline';

/**
 * Оглавление документа.
 *
 * Проверяется то, что ошибается молча: что считается заголовком, а что нет.
 * Лишняя строка в оглавлении — это обещание раздела, которого в тексте нет.
 */

function outline(text: string) {
  return outlineOf(Text.of(text.split('\n')));
}

function titles(text: string): string[] {
  return outline(text).map((h) => h.text);
}

describe('что считается заголовком', () => {
  it('решётки задают уровень', () => {
    const found = outline('# Первый\n\n## Второй\n\n###### Шестой\n');

    expect(found.map((h) => [h.level, h.text])).toEqual([
      [1, 'Первый'],
      [2, 'Второй'],
      [6, 'Шестой'],
    ]);
  });

  /**
   * Главное различие: тег с начала строки — не заголовок. В заметках так
   * пишут постоянно, и без пробела после решёток оглавление наполнилось бы
   * тегами.
   */
  it('тег заголовком не становится', () => {
    expect(titles('#работа\n\n# Настоящий\n')).toEqual(['Настоящий']);
  });

  it('семь решёток — уже не заголовок', () => {
    expect(titles('####### Слишком глубоко\n')).toEqual([]);
  });

  /** Хвостовая ограда — часть разметки, а не текста заголовка. */
  it('снимает хвостовые решётки', () => {
    expect(titles('## Заголовок ##\n')).toEqual(['Заголовок']);
  });

  it('пустой заголовок в список не идёт', () => {
    expect(titles('###\n\n# Настоящий\n')).toEqual(['Настоящий']);
  });

  /** Четыре пробела — блок кода отступом, а не заголовок. */
  it('отступ в четыре пробела делает строку кодом', () => {
    expect(titles('    # не заголовок\n\n   # заголовок\n')).toEqual(['заголовок']);
  });
});

describe('чего в оглавлении быть не должно', () => {
  /** `# комментарий` в примере на shell — комментарий, а не раздел. */
  it('решётка внутри огороженного блока', () => {
    const text = '# Настоящий\n\n```shell\n# комментарий\n```\n\n## Тоже настоящий\n';

    expect(titles(text)).toEqual(['Настоящий', 'Тоже настоящий']);
  });

  /** Ограда закрывается только такой же: `~~~` внутри ``` — обычный текст. */
  it('чужая ограда блок не закрывает', () => {
    const text = '```\n~~~\n# не заголовок\n```\n\n# заголовок\n';

    expect(titles(text)).toEqual(['заголовок']);
  });

  it('содержимое frontmatter', () => {
    const text = '---\ntitle: Заметка\n# не заголовок\n---\n\n# Заголовок\n';

    expect(titles(text)).toEqual(['Заголовок']);
  });

  /**
   * Три дефиса посреди текста — горизонтальная черта, а не начало
   * frontmatter: иначе половина документа исчезла бы из оглавления.
   */
  it('черта посреди текста frontmatter не открывает', () => {
    const text = '# Первый\n\n---\n\n# Второй\n';

    expect(titles(text)).toEqual(['Первый', 'Второй']);
  });
});

describe('куда ведёт строка оглавления', () => {
  it('смещение указывает на начало строки заголовка', () => {
    const text = 'Вступление\n\n## Раздел\n\nТекст\n';
    const found = outline(text);

    expect(found[0]!.line).toBe(3);
    expect(text.slice(found[0]!.from, found[0]!.from + 9)).toBe('## Раздел');
  });
});

describe('какой заголовок над курсором', () => {
  const items = outline('# Первый\n\nа\n\n## Второй\n\nб\n');

  it('выше первого заголовка — никакой', () => {
    expect(activeHeading(items, 1)).toBe(0);
    expect(activeHeading([], 5)).toBe(-1);
  });

  /** Текст под заголовком принадлежит ему до следующего. */
  it('текст раздела принадлежит своему заголовку', () => {
    expect(activeHeading(items, 3)).toBe(0);
    expect(activeHeading(items, 5)).toBe(1);
    expect(activeHeading(items, 7)).toBe(1);
  });

  it('курсор до первого заголовка ничего не подсвечивает', () => {
    const later = outline('Вступление\n\n# Первый\n');

    expect(activeHeading(later, 1)).toBe(-1);
  });
});
